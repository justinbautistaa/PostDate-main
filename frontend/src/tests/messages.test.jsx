import React from "react";
import { beforeEach, expect, it, vi } from "vitest";
import { render, screen, fireEvent, waitFor, within } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import Messages from "../pages/Messages";
import AppNav from "../components/AppNav";
import { setSession } from "../auth";
import * as chat from "../services/chatApi";
import api from "../api";
vi.mock("../api", () => ({ default: { post: vi.fn() } }));
vi.mock("../services/chatApi", () => ({ getConversations: vi.fn(), getConversation: vi.fn(), getMessages: vi.fn(), sendMessage: vi.fn(), getMatchedProfile: vi.fn() }));
const match = { id: "match-a", name: "Alex", avatarPath: null, lastMessage: "Hello!" };
beforeEach(() => {
  vi.resetAllMocks(); setSession({ userId: "me", role: "user" });
  chat.getConversations.mockResolvedValue({ conversations: [match], nextCursor: null });
  chat.getMessages.mockResolvedValue({ messages: [], nextCursor: null });
  chat.getConversation.mockRejectedValue({ response: { status: 404 } });
});
it("opens an older conversation directly from a notification without paging through matches", async () => {
  chat.getConversation.mockResolvedValue({ ...match, id: "older-match", name: "Older match" });
  render(<MemoryRouter initialEntries={["/messages?match=older-match"]}><Messages /></MemoryRouter>);
  expect(await screen.findByRole("textbox", { name: "Message to Older match" })).toBeTruthy();
  expect(chat.getConversation).toHaveBeenCalledWith("older-match");
  await waitFor(() => expect(chat.getMessages).toHaveBeenCalledWith("older-match"));
});
it("explains unavailable notification targets without displaying another conversation", async () => {
  render(<MemoryRouter initialEntries={["/messages?match=missing-match"]}><Messages /></MemoryRouter>);
  expect((await screen.findByRole("alert")).textContent).toContain("no longer available");
  expect(screen.queryByRole("textbox", { name: "Message to Alex" })).toBeNull();
});
it.each([["user", null], ["moderator", "Staff"], ["admin", "Admin"]])("%s gets the right navigation", (role, workspace) => {
  setSession({ userId: "me", role });
  render(<MemoryRouter><AppNav /></MemoryRouter>);
  const nav = screen.getByRole("navigation", { name: "Main" });
  expect(within(nav).getByRole("link", { name: "Find dates" }).getAttribute("href")).toBe("/discover");
  expect(within(nav).getByRole("link", { name: "Chats" }).getAttribute("href")).toBe("/messages");
  if (workspace) expect(within(nav).getByRole("link", { name: workspace })).toBeTruthy();
  else expect(within(nav).queryByRole("link", { name: /Admin|Staff/ })).toBeNull();
});
it("explains that chats begin with a mutual match", async () => {
  chat.getConversations.mockResolvedValue({ conversations: [], nextCursor: null });
  render(<MemoryRouter><Messages /></MemoryRouter>);
  await screen.findByText(/When you both like each other/);
  expect(chat.getMessages).not.toHaveBeenCalled();
});
it("refreshes the conversation list when connection notifications change", async () => {
  render(<MemoryRouter><Messages /></MemoryRouter>);
  await screen.findByRole("button", { name: "Chat with Alex" });
  chat.getConversations.mockResolvedValue({ conversations: [match, { ...match, id: "match-b", name: "Bea" }], nextCursor: null });
  fireEvent(window, new Event("postdate:connections-updated"));
  expect(await screen.findByRole("button", { name: "Chat with Bea" })).toBeTruthy();
});
it("opens the compact menu and closes it after navigation or Escape", () => {
  render(<MemoryRouter><AppNav /></MemoryRouter>);
  fireEvent.click(screen.getByRole("button", { name: "Open menu" }));
  expect(screen.getByRole("button", { name: "Close menu" }).getAttribute("aria-expanded")).toBe("true");
  fireEvent.keyDown(screen.getByRole("button", { name: "Close menu" }), { key: "Escape" });
  expect(screen.getByRole("button", { name: "Open menu" }).getAttribute("aria-expanded")).toBe("false");
  fireEvent.click(screen.getByRole("button", { name: "Open menu" }));
  fireEvent.click(screen.getByRole("link", { name: "My reports" }));
  expect(screen.getByRole("button", { name: "Open menu" }).getAttribute("aria-expanded")).toBe("false");
});
it("opens a match, persists a message, and displays server-confirmed text", async () => {
  chat.sendMessage.mockResolvedValue({ id: "msg-1", text: "Hi Alex", mine: true, sentAt: "2026-10-15T12:00:00Z" });
  render(<MemoryRouter><Messages /></MemoryRouter>);
  fireEvent.click(await screen.findByRole("button", { name: "Chat with Alex" }));
  const input = await screen.findByRole("textbox", { name: "Message to Alex" });
  await waitFor(() => expect(input.disabled).toBe(false));
  fireEvent.change(input, { target: { value: "Hi Alex" } });
  fireEvent.click(screen.getByRole("button", { name: "Send ↗" }));
  await screen.findByText("Hi Alex");
  expect(chat.sendMessage).toHaveBeenCalledWith("match-a", "Hi Alex");
  expect(input.value).toBe("");
});
it("preserves the draft when sending fails", async () => {
  chat.sendMessage.mockRejectedValue(new Error("offline"));
  render(<MemoryRouter initialEntries={["/messages?match=match-a"]}><Messages /></MemoryRouter>);
  const input = await screen.findByRole("textbox", { name: "Message to Alex" });
  await waitFor(() => expect(input.disabled).toBe(false));
  fireEvent.change(input, { target: { value: "Still here" } });
  fireEvent.click(screen.getByRole("button", { name: "Send ↗" }));
  await screen.findByRole("alert");
  expect(input.value).toBe("Still here");
  expect(screen.queryByText("Still here", { selector: ".chat-message p" })).toBeNull();
});
it("views the chat partner's profile and returns to the same unsent draft", async () => {
  chat.getMatchedProfile.mockResolvedValue({ id: "user-alex", name: "Alex", age: 25, bio: "Loves a good book", tags: ["Hiking"], lookingFor: ["Friendship"], photoPaths: [] });
  render(<MemoryRouter initialEntries={["/messages?match=match-a"]}><Messages /></MemoryRouter>);
  const draft = await screen.findByRole("textbox", { name: "Message to Alex" });
  await waitFor(() => expect(draft.disabled).toBe(false));
  fireEvent.change(draft, { target: { value: "My unsent hello" } });
  fireEvent.click(screen.getByRole("button", { name: "View profile" }));
  await screen.findByText("Loves a good book");
  expect(screen.getByText("Hiking")).toBeTruthy();
  expect(chat.getMatchedProfile).toHaveBeenCalledWith("match-a");
  fireEvent.click(screen.getByRole("button", { name: "Close profile" }));
  expect(screen.queryByRole("dialog")).toBeNull();
  expect(draft.value).toBe("My unsent hello");
});
it("renders message HTML as text", async () => {
  const text = '<img src=x onerror="alert(1)">';
  chat.getMessages.mockResolvedValue({ messages: [{ id: "msg-1", text, mine: false, sentAt: "2026-10-15T12:00:00Z" }], nextCursor: null });
  const { container } = render(<MemoryRouter initialEntries={["/messages?match=match-a"]}><Messages /></MemoryRouter>);
  await screen.findByText(text);
  expect(container.querySelector("img[onerror]")).toBeNull();
});
it("saves a rating for the selected chat and keeps the draft", async () => {
  chat.getMatchedProfile.mockResolvedValue({ id: "user-alex", name: "Alex", tags: [], photoPaths: [] });
  api.post.mockResolvedValue({ data: { reviewed: true } });
  render(<MemoryRouter initialEntries={["/messages?match=match-a"]}><Messages /></MemoryRouter>);
  const draft = await screen.findByRole("textbox", { name: "Message to Alex" });
  await waitFor(() => expect(draft.disabled).toBe(false));
  fireEvent.change(draft, { target: { value: "See you soon" } });
  expect(screen.queryByRole("button", { name: "Rate your experience" })).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "View profile" }));
  fireEvent.click(await screen.findByRole("button", { name: "Rate your experience" }));
  const dialog = screen.getByRole("dialog");
  within(dialog).getAllByRole("combobox").forEach(select => fireEvent.change(select, { target: { value: "4" } }));
  fireEvent.click(within(dialog).getByRole("button", { name: "Submit review" }));
  await screen.findByText("Your rating was saved. Thank you for your feedback.");
  expect(api.post).toHaveBeenCalledWith("/reviews", { matchId: "match-a", ratings: { overall: 4, spice: 4, attentiveness: 4, respectfulness: 4, chemistry: 4 }, comment: "", isPublic: true });
  expect(screen.queryByRole("button", { name: "Rate your experience" })).toBeNull();
  expect(draft.value).toBe("See you soon");
});
it("shows a previously saved rating after reopening a chat", async () => {
  chat.getMatchedProfile.mockResolvedValue({ id: "user-alex", name: "Alex", tags: [], photoPaths: [] });
  chat.getMessages.mockResolvedValue({ messages: [], nextCursor: null, reviewed: true });
  render(<MemoryRouter initialEntries={["/messages?match=match-a"]}><Messages /></MemoryRouter>);
  fireEvent.click(await screen.findByRole("button", { name: "View profile" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "Rated ✓" }).disabled).toBe(true));
});
it("rates from the chat partner profile and shows the saved state there", async () => {
  chat.getMatchedProfile.mockResolvedValue({ id: "user-alex", name: "Alex", tags: [], photoPaths: [] });
  api.post.mockResolvedValue({ data: { reviewed: true } });
  render(<MemoryRouter initialEntries={["/messages?match=match-a"]}><Messages /></MemoryRouter>);
  const draft = await screen.findByRole("textbox", { name: "Message to Alex" });
  await waitFor(() => expect(draft.disabled).toBe(false));
  fireEvent.change(draft, { target: { value: "Talk soon" } });
  fireEvent.click(screen.getByRole("button", { name: "View profile" }));
  const profile = await screen.findByRole("dialog");
  fireEvent.click(await within(profile).findByRole("button", { name: "Rate your experience" }));
  const review = screen.getByRole("dialog", { name: "Your experience with Alex" });
  within(review).getAllByRole("combobox").forEach(select => fireEvent.change(select, { target: { value: "5" } }));
  fireEvent.click(within(review).getByRole("button", { name: "Submit review" }));
  await screen.findByText("Your rating was saved. Thank you for your feedback.");
  expect(draft.value).toBe("Talk soon");
  fireEvent.click(screen.getByRole("button", { name: "View profile" }));
  const reopened = await screen.findByRole("dialog");
  await waitFor(() => expect(within(reopened).getByRole("button", { name: "Rated ✓" }).disabled).toBe(true));
});
it("confirms blocking from the matched profile before removing the conversation", async () => {
  chat.getMatchedProfile.mockResolvedValue({ id: "user-alex", name: "Alex", tags: [], photoPaths: [] });
  api.post.mockResolvedValue({});
  render(<MemoryRouter initialEntries={["/messages?match=match-a"]}><Messages /></MemoryRouter>);
  fireEvent.click(await screen.findByRole("button", { name: "View profile" }));
  fireEvent.click(await screen.findByRole("button", { name: "Block person" }));
  expect(api.post).not.toHaveBeenCalledWith("/chats/match-a/block");
  fireEvent.click(screen.getByRole("button", { name: "Keep match" }));
  expect(screen.queryByRole("button", { name: "Confirm block" })).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "Block person" }));
  chat.getConversations.mockResolvedValue({ conversations: [], nextCursor: null });
  fireEvent.click(screen.getByRole("button", { name: "Confirm block" }));
  await waitFor(() => expect(api.post).toHaveBeenCalledWith("/chats/match-a/block"));
  await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
});
