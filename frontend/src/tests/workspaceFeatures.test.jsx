import React from "react";
import { beforeEach, expect, it, vi } from "vitest";
import { render, screen, fireEvent, waitFor } from "@testing-library/react";
import WorkspaceFeatures from "../components/WorkspaceFeatures";
import api from "../api";
import { getAdminUsers } from "../services/adminApi";
import { subscribeToNotices } from "../services/noticeLive";
vi.mock("../services/noticeLive", () => ({ subscribeToNotices: vi.fn(() => () => {}) }));
vi.mock("../api", () => ({ default: { get: vi.fn(), post: vi.fn(), patch: vi.fn(), delete: vi.fn() } }));
vi.mock("../services/adminApi", () => ({ getAdminUsers: vi.fn(), errorMessage: err => err.message }));
const plan = { id: "plan1", title: "Coffee", body: "Central cafe", when: "2099-10-15T10:00:00Z", done: false };
beforeEach(() => {
  vi.resetAllMocks(); api.get.mockResolvedValue({ data: [] });
  getAdminUsers.mockResolvedValue({ rows: [{ id: "member1", name: "Alex Test", email: "alex@example.test" }] });
  subscribeToNotices.mockReturnValue(() => {});
});
it("updates notices on a live event and unsubscribes when leaving", async () => {
  const close = vi.fn();
  let changed;
  subscribeToNotices.mockImplementation(callback => { changed = callback; return close; });
  const { unmount } = render(<WorkspaceFeatures kind="announcements" />);
  await screen.findByText(/all caught up/);
  api.get.mockResolvedValue({ data: [{ id: "live", title: "New announcement", body: "Just published", audience: "everyone", createdAt: "2026-10-16" }] });
  await changed();
  await screen.findByText("New announcement");
  api.get.mockResolvedValue({ data: [] });
  await changed();
  await screen.findByText(/all caught up/);
  unmount();
  expect(close).toHaveBeenCalledOnce();
});
it("members and staff can read notices but cannot see publishing controls", async () => {
  api.get.mockResolvedValue({ data: [{ id: "notice", title: "Welcome", body: "Be kind", audience: "everyone", createdAt: "2026-10-15" }] });
  render(<WorkspaceFeatures kind="announcements" role="moderator" />);
  await screen.findByText("Welcome");
  expect(screen.queryByRole("button", { name: "Publish notice" })).toBeNull();
  expect(screen.queryByRole("button", { name: "Delete" })).toBeNull();
});
it("admin publishes audience-specific announcements", async () => {
  api.post.mockResolvedValue({ data: { id: "new", title: "Team news", body: "Hello team", audience: "staff", createdAt: "2026-10-15" } });
  render(<WorkspaceFeatures kind="announcements" role="admin" />);
  await screen.findByText(/all caught up/);
  fireEvent.change(screen.getByLabelText("Title"), { target: { value: "Team news" } });
  fireEvent.change(screen.getByLabelText("Message"), { target: { value: "Hello team" } });
  fireEvent.change(screen.getByLabelText("Audience"), { target: { value: "staff" } });
  fireEvent.click(screen.getByRole("button", { name: "Publish notice" }));
  await screen.findByText("Notice published.");
  expect(api.post).toHaveBeenCalledWith("/workspace/announcements", { title: "Team news", body: "Hello team", audience: "staff" });
});
it("staff choose a member, save a follow-up, and complete it", async () => {
  const note = { id: "note1", title: "Check in", body: "Account question", member: { id: "member1", name: "Alex Test" }, done: false };
  api.post.mockResolvedValue({ data: note }); api.patch.mockResolvedValue({ data: { ...note, done: true } });
  render(<WorkspaceFeatures kind="notes" role="moderator" />);
  await screen.findByRole("option", { name: /Alex Test/ });
  fireEvent.change(screen.getByLabelText("Title"), { target: { value: note.title } });
  fireEvent.change(screen.getByLabelText("Internal note"), { target: { value: note.body } });
  fireEvent.change(screen.getByLabelText("Member"), { target: { value: "member1" } });
  fireEvent.click(screen.getByRole("button", { name: "Add follow-up" }));
  await screen.findByText("Follow-up saved for the team.");
  expect(api.post).toHaveBeenCalledWith("/workspace/notes", { title: note.title, body: note.body, member: "member1" });
  fireEvent.click(screen.getByRole("button", { name: "Mark complete" }));
  await screen.findByText("Marked complete.");
  fireEvent.click(screen.getByRole("button", { name: "Completed" }));
  expect(screen.getByText("Check in")).toBeTruthy();
});
it("members can save, edit and delete a date plan", async () => {
  api.post.mockResolvedValue({ data: plan }); api.patch.mockResolvedValue({ data: { ...plan, title: "Dinner" } }); api.delete.mockResolvedValue({});
  vi.spyOn(window, "confirm").mockReturnValue(true);
  render(<WorkspaceFeatures kind="plans" />);
  await screen.findByText(/Add your first date plan/);
  fireEvent.change(screen.getByLabelText("Title"), { target: { value: "Coffee" } });
  fireEvent.change(screen.getByLabelText("Place and details"), { target: { value: "Central cafe" } });
  fireEvent.change(screen.getByLabelText("Date and time (your local time)"), { target: { value: "2099-10-15T10:00" } });
  fireEvent.click(screen.getByRole("button", { name: "Save date plan" }));
  await screen.findByText("Your date plan is saved.");
  expect(api.post).toHaveBeenCalledWith("/workspace/plans", expect.objectContaining({ title: "Coffee", when: new Date("2099-10-15T10:00").toISOString() }));
  fireEvent.click(screen.getByRole("button", { name: "Edit" }));
  fireEvent.change(screen.getByLabelText("Title"), { target: { value: "Dinner" } });
  fireEvent.click(screen.getByRole("button", { name: "Update date plan" }));
  await screen.findByText("Dinner");
  fireEvent.click(screen.getByRole("button", { name: "Delete" }));
  await waitFor(() => expect(api.delete).toHaveBeenCalledWith("/workspace/plan1"));
  await screen.findByText("Entry deleted.");
});
it("save failures retain the draft for retry", async () => {
  api.post.mockRejectedValue(new Error("Offline"));
  render(<WorkspaceFeatures kind="announcements" role="admin" />);
  await screen.findByText(/all caught up/);
  fireEvent.change(screen.getByLabelText("Title"), { target: { value: "Keep this draft" } });
  fireEvent.click(screen.getByRole("button", { name: "Publish notice" }));
  await screen.findByRole("alert");
  expect(screen.getByLabelText("Title").value).toBe("Keep this draft");
});
